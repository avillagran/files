pub fn mime(path: &Path) -> &'static str {
    let ext = path
        .extension()
        .unwrap_or_default()
        .to_string_lossy()
        .to_ascii_lowercase();
    TABLE
        .binary_search_by_key(&ext.as_str(), |&(e, _)| e)
        .map(|i| TABLE[i].1)
        .unwrap_or("application/octet-stream")
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn table_integrity() {
        assert!(TABLE.len() >= 300);
        assert!(TABLE.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(mime(Path::new("a.PNG")), "image/png");
        assert_eq!(mime(Path::new("a.unknown")), "application/octet-stream");
    }
}
